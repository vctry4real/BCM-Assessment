
document.addEventListener("DOMContentLoaded", () => {
  const article = document.querySelector("article");
  const addButton = document.querySelector("#add-paragraphs");

  if (!article || !addButton) {
    console.error("Required article or button was not found.");
    return;
  }

  // Capture the three original paragraphs before any copies are added.
  const originalParagraphs = Array.from(
    article.querySelectorAll("p")
  );

  let imagesHidden = false;

  // Create the second button using JavaScript only.
  const toggleButton = document.createElement("button");
  toggleButton.type = "button";
  toggleButton.textContent = "Hide image paragraphs";
  toggleButton.setAttribute("aria-pressed", "false");

  const controls = document.createElement("div");
  controls.className = "controls";
  controls.append(addButton, toggleButton);

  article.append(controls);

  function getAllParagraphs() {
    return Array.from(article.querySelectorAll("p"));
  }

  function rebuildSeparators() {
    // Remove separators generated by previous runs.
    article.querySelectorAll("hr[data-generated]").forEach((hr) => {
      hr.remove();
    });

    // Count every paragraph, including hidden paragraphs.
    const paragraphs = getAllParagraphs();

    paragraphs.forEach((paragraph, index) => {
      const isEndOfPair = (index + 1) % 2 === 0;
      const hasAnotherParagraph = index < paragraphs.length - 1;

      if (isEndOfPair && hasAnotherParagraph) {
        const hr = document.createElement("hr");
        hr.dataset.generated = "true";
        paragraph.after(hr);
      }
    });
  }

  function applyImageVisibility() {
    getAllParagraphs().forEach((paragraph) => {
      const containsImage = paragraph.querySelector("img");

      if (containsImage) {
        paragraph.hidden = imagesHidden;
      }
    });

    toggleButton.textContent = imagesHidden
      ? "Show image paragraphs"
      : "Hide image paragraphs";

    toggleButton.setAttribute(
      "aria-pressed",
      String(imagesHidden)
    );
  }

  function shuffle(items) {
    const result = [...items];

    // Fisher–Yates shuffle.
    for (let i = result.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));

      [result[i], result[j]] = [result[j], result[i]];
    }

    return result;
  }

  function cloneParagraph(paragraph) {
    const clone = paragraph.cloneNode(true);

    // Do not duplicate IDs from the original HTML.
    clone.removeAttribute("id");

    return clone;
  }

  addButton.addEventListener("click", () => {
    const copies = shuffle(originalParagraphs).map(
      cloneParagraph
    );

    // Insert copies before the controls, preserving their position.
    copies.forEach((paragraph) => {
      controls.before(paragraph);
    });

    // New image paragraphs inherit the current visibility state.
    applyImageVisibility();
    rebuildSeparators();
  });

  toggleButton.addEventListener("click", () => {
    imagesHidden = !imagesHidden;

    applyImageVisibility();
    rebuildSeparators();
  });

  // Apply the separator rule to the initial three paragraphs.
  rebuildSeparators();
});
